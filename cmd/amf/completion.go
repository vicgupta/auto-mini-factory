const completionHelp = `Usage:
  amf completion <bash|zsh|fish>

Prints a shell completion script for commands, subcommands and flags.
Needs no configuration or GitHub access. Source the script in your shell:

  bash: source <(amf completion bash)   # add to ~/.bashrc
  zsh:  source <(amf completion zsh)    # after compinit in ~/.zshrc
  fish: amf completion fish | source   # add to ~/.config/fish/config.fish
`

func cmdCompletion(args []string, stdout, stderr io.Writer) error {
	pos, err := parseArgs(newCommandFlags("completion", stderr), args)
	if err != nil {
		if err == flag.ErrHelp {
			return nil
		}
		return errUsage
	}
	if len(pos) != 1 || !slices.Contains([]string{"bash", "zsh", "fish"}, pos[0]) {
		fmt.Fprint(stderr, completionHelp)
		return errUsage
	}
	_, err = io.WriteString(stdout, completionScriptFor(pos[0]))
	return err
}

// completionOptions lists visible flags; a trailing = marks a required value
// so words used as flag values are never mistaken for subcommands. Short forms
// and command groups come from the same lists as help and flag parsing.
func completionOptions() map[string][]string {
	const memory = "memory-backend= memory-dir="
	const run = "agent-timeout= eval-rounds= agent= draft merge wait-for-checks dry-run force log-level= log-file= " + memory
	const watch = "agent-timeout= interval= label= exclude-label= eval-rounds= agent= draft merge wait-for-checks stale-timeout= log-level= log-file= " + memory
	flags := map[string]string{
		"init": "", "version": "", "completion": "",
		"run": run, "issue run": run, "watch": watch, "issue watch": watch,
		"auto":          "agent-timeout= eval-rounds= agent= max-issues= merge continue no-checkpoint checkpoint-after= approve wait-for-checks abort close-issues dry-run log-level= log-file= " + memory,
		"issue create":  "body= file= label= no-label",
		"issue list":    "state= label= search= limit= json",
		"list":          "state= label= search= limit= json",
		"issue label":   "add= remove= state= label= unlabeled",
		"issue unlabel": "state= label= unlabeled",
		"issue close":   "comment= delete-branch", "issue reopen": "", "issue view": "json",
		"pr list":  "state= limit= issue= json",
		"pr merge": "squash rebase delete-branch update-branch wait-for-checks",
		"pr sweep": "merge wait-for-checks dry-run json",
		"pr view":  "json", "pr diff": "name-only",
		"pr close": "comment= delete-branch", "pr reopen": "", "pr ready": "", "pr draft": "",
		"auth login":  "host= client-id= scopes= no-browser",
		"auth status": "host=", "auth logout": "host=", "auth token": "host= force",
		"memory sync": memory + " json limit= full", "memory similar": memory + " json limit= full", "memory show": memory + " json limit= full",
		"pipeline": "fetch", "doctor": "fix-labels", "update": "version= check",
	}
	options := map[string][]string{
		"":            append(slices.Clone(topCommands), "--version"),
		"completion":  {"bash", "zsh", "fish"},
		"auto":        {"status"},
		"auto status": {},
		"help":        topicNames(),
	}
	for group, subs := range helpSubcommands {
		options[group] = slices.Clone(subs)
		options["help "+group] = slices.Clone(subs)
	}
	// memory accepts only these three subcommands (its help is a topic).
	options["memory"] = []string{"sync", "similar", "show"}
	for key, names := range flags {
		for _, name := range strings.Fields(names) {
			options[key] = append(options[key], "--"+name)
			long := strings.TrimSuffix(name, "=")
			if short := shortFlags[long]; short != "" {
				options[key] = append(options[key], "-"+short+strings.TrimPrefix(name, long))
			}
		}
	}
	return options
}

func completionScriptFor(shell string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# amf %s completion; generated by amf completion %s\n", shell, shell)
	options := completionOptions()
	var keys []string
	for key := range options {
		keys = append(keys, key)
	}
	slices.Sort(keys)
	if shell == "fish" {
		b.WriteString("function _amf_options\n    switch \"$argv[1]\"\n")
	} else {
		b.WriteString("_amf_options() {\n    case \"$1\" in\n")
	}
	const global = " --quiet -q --color= -O= --dir= --env-file= --clone-dir= --help -h"
	for _, key := range keys {
		words := strings.Join(options[key], " ") + global
		if shell == "fish" {
			fmt.Fprintf(&b, "        case '%s'\n            echo '%s'\n", key, words)
		} else {
			fmt.Fprintf(&b, "        '%s') printf '%%s\\n' '%s' ;;\n", key, words)
		}
	}
	if shell == "fish" {
		fmt.Fprintf(&b, "        case '*'\n            echo '%s'\n    end\nend\n", global)
		b.WriteString(fishCompletion)
		return b.String()
	}
	fmt.Fprintf(&b, "        *) printf '%%s\\n' '%s' ;;\n    esac\n}\n", global)
	b.WriteString(shCompletionCandidates)
	if shell == "bash" {
		b.WriteString(bashCompletion)
	} else {
		b.WriteString(zshCompletion)
	}
	return b.String()
}

const shCompletionCandidates = `
_amf_candidates() {
    local context='' pending='' word options
    for word in "$@"; do
        if [ -n "$pending" ]; then
            [ "$word" = '=' ] && continue
            pending=''
            continue
        fi
        options="$(_amf_options "$context")"
        case "$word" in
            --) return 0 ;;
            -*=*) ;;
            -*) case " $options " in *" $word= "*) pending=1 ;; esac ;;
            *) case " $options " in
                *" $word "*) context="${context:+$context }$word" ;;
                *) [ "$context" = issue ] && context='issue create' ;;
            esac ;;
        esac
    done
    [ -n "$pending" ] && return 0
    options="$(_amf_options "$context")"
    printf '%s\n' "${options//=/}"
}
`

const bashCompletion = `
_amf_complete() {
    local word
    COMPREPLY=()
    while IFS= read -r word; do
        COMPREPLY+=("$word")
    done < <(compgen -W "$(_amf_candidates "${COMP_WORDS[@]:1:COMP_CWORD-1}")" -- "${COMP_WORDS[COMP_CWORD]}")
}
complete -o default -F _amf_complete amf
`

const zshCompletion = `
_amf_complete() {
    local -a candidates
    candidates=(${(s: :)$(_amf_candidates "${words[@]:1:$((CURRENT-2))}")})
    if (( ${#candidates[@]} )); then
        compadd -- "${candidates[@]}"
    else
        _files
    fi
}
compdef _amf_complete amf
`

const fishCompletion = `
function _amf_candidates
    set -l context ''
    set -l pending ''
    for word in $argv
        if test -n "$pending"
            set pending ''
            continue
        end
        set -l options (string split ' ' -- (_amf_options "$context"))
        switch "$word"
            case --
                return
            case '-*=*'
            case '-*'
                if contains -- "$word=" $options
                    set pending 1
                end
            case '*'
                if contains -- "$word" $options
                    set context (string join ' ' -- "$context" "$word" | string trim)
                else if test "$context" = issue
                    set context 'issue create'
                end
        end
    end
    if test -z "$pending"
        string replace -a '=' '' -- (string split ' ' -- (_amf_options "$context"))
    end
end
complete -c amf -f -a '(_amf_candidates (commandline -opc)[2..-1])'
`
