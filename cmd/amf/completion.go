const completionHelp = `Usage:
  amf completion <bash|zsh|fish>

Prints a shell completion script for commands, subcommands and flags.
Needs no configuration or GitHub access. Source the script in your shell:

  bash: source <(amf completion bash)   # add to ~/.bashrc
  zsh:  source <(amf completion zsh)    # after compinit in ~/.zshrc
  fish: amf completion fish | source   # add to ~/.config/fish/config.fish
`

func cmdCompletion(args []string, stdout, stderr io.Writer) error {
	pos, err := parseArgs(newCommandFlags("completion", stderr), args)
	if err != nil {
		if err == flag.ErrHelp {
			return nil
		}
		return errUsage
	}
	if len(pos) != 1 || !slices.Contains([]string{"bash", "zsh", "fish"}, pos[0]) {
		fmt.Fprint(stderr, completionHelp)
		return errUsage
	}
	_, err = io.WriteString(stdout, completionScriptFor(pos[0]))
	return err
}

// completionOptions lists visible flags; a trailing = marks a required value
// so words used as flag values are never mistaken for subcommands. Command
// flags come from the same FlagSets that help and parsing use, so a new flag
// needs no completion change. Short forms and command groups come from the
// same lists as help and flag parsing.
func completionOptions() map[string][]string {
	options := map[string][]string{
		"":            append(slices.Clone(topCommands), "--version"),
		"completion":  {"bash", "zsh", "fish"},
		"auto":        {"status"},
		"auto status": {},
		"help":        topicNames(),
	}
	for group, subs := range helpSubcommands {
		options[group] = slices.Clone(subs)
		options["help "+group] = slices.Clone(subs)
	}
	// memory accepts only these three subcommands (its help is a topic).
	options["memory"] = []string{"sync", "similar", "show"}
	for key := range helpArgs {
		if _, ok := options[key]; !ok {
			options[key] = nil // commands without flags still get a case
		}
		options[key] = append(options[key], completionCommandFlags(completionCommandFlagSet(key))...)
	}
	global := completionGlobalFlags()
	for key := range options {
		options[key] = append(options[key], global...)
	}
	return options
}

// completionCommandFlags lists fs's visible flags, from the same FlagSet help
// prints. Path flags are global, so they are added once per command by
// completionGlobalFlags.
func completionCommandFlags(fs *flag.FlagSet) []string {
	var words []string
	fs.VisitAll(func(f *flag.Flag) {
		if hiddenFlags[f.Name] || pathFlags[f.Name] {
			return
		}
		suffix := ""
		if bf, ok := f.Value.(interface{ IsBoolFlag() bool }); !ok || !bf.IsBoolFlag() {
			suffix = "="
		}
		words = append(words, "--"+f.Name+suffix)
		if short := shortFor(fs, f.Name); short != "" {
			words = append(words, "-"+short+suffix)
		}
	})
	return words
}

// completionCommandFlagSet builds a command's own FlagSet without running it.
func completionCommandFlagSet(key string) *flag.FlagSet {
	fs := newCommandFlags(key, io.Discard)
	switch key {
	case "run", "issue run":
		addRunFlags(fs)
	case "watch", "issue watch":
		addWatchFlags(fs)
	case "auto":
		addAutoFlags(fs)
	case "issue create":
		addIssueCreateFlags(fs)
	case "issue list", "list":
		addListFlags(fs)
	case "issue label":
		addIssueLabelFlags(fs, "label")
	case "issue unlabel":
		addIssueLabelFlags(fs, "unlabel")
	case "issue close":
		addIssueStateFlags(fs, "close")
	case "issue reopen":
		addIssueStateFlags(fs, "reopen")
	case "issue view":
		addIssueViewFlags(fs)
	case "pr list":
		addPRListFlags(fs)
	case "pr merge":
		addPRMergeFlags(fs)
	case "pr sweep":
		addPRSweepFlags(fs)
	case "pr view":
		addPRViewFlags(fs)
	case "pr diff":
		addPRDiffFlags(fs)
	case "pr comment":
		addPRCommentFlags(fs)
	case "pr close":
		addPRCloseFlags(fs)
	case "auth login", "auth status", "auth logout", "auth token":
		addAuthFlags(fs, strings.TrimPrefix(key, "auth "))
	case "memory sync", "memory similar", "memory show":
		addMemoryCommandFlags(fs)
	case "pipeline":
		addPipelineFlags(fs)
	case "doctor":
		addDoctorFlags(fs)
	case "update":
		addUpdateFlags(fs)
	}
	return fs
}

// completionGlobalFlags lists the flags every command's completion offers,
// from the same FlagSet help prints.
func completionGlobalFlags() []string {
	fs := globalFlagSet()
	var words []string
	fs.VisitAll(func(f *flag.Flag) {
		if hiddenFlags[f.Name] {
			return
		}
		suffix := ""
		if bf, ok := f.Value.(interface{ IsBoolFlag() bool }); !ok || !bf.IsBoolFlag() {
			suffix = "="
		}
		words = append(words, "--"+f.Name+suffix)
		if short := shortFor(fs, f.Name); short != "" {
			words = append(words, "-"+short+suffix)
		}
	})
	return append(words, "--help", "-h")
}

func completionScriptFor(shell string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# amf %s completion; generated by amf completion %s\n", shell, shell)
	options := completionOptions()
	var keys []string
	for key := range options {
		keys = append(keys, key)
	}
	slices.Sort(keys)
	if shell == "fish" {
		b.WriteString("function _amf_options\n    switch \"$argv[1]\"\n")
	} else {
		b.WriteString("_amf_options() {\n    case \"$1\" in\n")
	}
	global := strings.Join(completionGlobalFlags(), " ")
	for _, key := range keys {
		words := strings.Join(options[key], " ")
		if shell == "fish" {
			fmt.Fprintf(&b, "        case '%s'\n            echo '%s'\n", key, words)
		} else {
			fmt.Fprintf(&b, "        '%s') printf '%%s\\n' '%s' ;;\n", key, words)
		}
	}
	if shell == "fish" {
		fmt.Fprintf(&b, "        case '*'\n            echo '%s'\n    end\nend\n", global)
		b.WriteString(fishCompletion)
		return b.String()
	}
	fmt.Fprintf(&b, "        *) printf '%%s\\n' '%s' ;;\n    esac\n}\n", global)
	b.WriteString(shCompletionCandidates)
	if shell == "bash" {
		b.WriteString(bashCompletion)
	} else {
		b.WriteString(zshCompletion)
	}
	return b.String()
}

const shCompletionCandidates = `
_amf_candidates() {
    local context='' pending='' word options
    for word in "$@"; do
        if [ -n "$pending" ]; then
            [ "$word" = '=' ] && continue
            pending=''
            continue
        fi
        options="$(_amf_options "$context")"
        case "$word" in
            --) return 0 ;;
            -*=*) ;;
            -*) case " $options " in *" $word= "*) pending=1 ;; esac ;;
            *) case " $options " in
                *" $word "*) context="${context:+$context }$word" ;;
                *) [ "$context" = issue ] && context='issue create' ;;
            esac ;;
        esac
    done
    [ -n "$pending" ] && return 0
    options="$(_amf_options "$context")"
    printf '%s\n' "${options//=/}"
}
`

const bashCompletion = `
_amf_complete() {
    local word
    COMPREPLY=()
    while IFS= read -r word; do
        COMPREPLY+=("$word")
    done < <(compgen -W "$(_amf_candidates "${COMP_WORDS[@]:1:COMP_CWORD-1}")" -- "${COMP_WORDS[COMP_CWORD]}")
}
complete -o default -F _amf_complete amf
`

const zshCompletion = `
_amf_complete() {
    local -a candidates
    candidates=(${(s: :)$(_amf_candidates "${words[@]:1:$((CURRENT-2))}")})
    if (( ${#candidates[@]} )); then
        compadd -- "${candidates[@]}"
    else
        _files
    fi
}
compdef _amf_complete amf
`

const fishCompletion = `
function _amf_candidates
    set -l context ''
    set -l pending ''
    for word in $argv
        if test -n "$pending"
            set pending ''
            continue
        end
        set -l options (string split ' ' -- (_amf_options "$context"))
        switch "$word"
            case --
                return
            case '-*=*'
            case '-*'
                if contains -- "$word=" $options
                    set pending 1
                end
            case '*'
                if contains -- "$word" $options
                    set context (string join ' ' -- "$context" "$word" | string trim)
                else if test "$context" = issue
                    set context 'issue create'
                end
        end
    end
    if test -z "$pending"
        string replace -a '=' '' -- (string split ' ' -- (_amf_options "$context"))
    end
end
complete -c amf -f -a '(_amf_candidates (commandline -opc)[2..-1])'
`
